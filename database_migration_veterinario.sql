-- 2. TABELA DE CANIS FÍSICOS (Instalações, Baias, Boxes e Canis)
CREATE TABLE IF NOT EXISTS `CANIS_FISICOS` (
  `ID_CANIL` VARCHAR(64) NOT NULL,
  `NOME_CANIL` VARCHAR(255) NOT NULL,
  `IDENTIFICACAO_CANIL` VARCHAR(64) DEFAULT NULL,
  `CAPACIDADE_CANIL` INT NOT NULL DEFAULT 1,
  `LOCALIZACAO_CANIL` VARCHAR(255) DEFAULT NULL,
  `DEPARTAMENTO_ID_CANIL` VARCHAR(64) DEFAULT NULL,
  `UNIDADE_ID_CANIL` VARCHAR(64) DEFAULT NULL,
  `STATUS_CANIL` ENUM('Ativo', 'Em Manutenção', 'Inativo') NOT NULL DEFAULT 'Ativo',
  `OBSERVACOES_CANIL` TEXT DEFAULT NULL,
  `DATA_CRIACAO_CANIL` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`ID_CANIL`),
  KEY `idx_canil_dept` (`DEPARTAMENTO_ID_CANIL`),
  KEY `idx_canil_unit` (`UNIDADE_ID_CANIL`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

