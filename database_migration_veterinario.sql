);

SET @sql = IF(@column_exists = 0, 
  'ALTER TABLE `USUARIOS` ADD COLUMN `ROLES_USUARIOS` TEXT NULL COMMENT "JSON array com múltiplos papéis do usuário" AFTER `PERFIL_USUARIOS`', 
  'SELECT "Coluna ROLES_USUARIOS já existe."'
