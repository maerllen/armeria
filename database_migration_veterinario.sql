  `UNIDADE_ID_PRODUTO_VET` VARCHAR(64) DEFAULT NULL,
  `OBSERVACOES_PRODUTO_VET` TEXT DEFAULT NULL,
  `DATA_CRIACAO_PRODUTO_VET` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`ID_PRODUTO_VET`),
  KEY `idx_prod_cod_barras` (`CODIGO_BARRAS_PRODUTO_VET`),
  KEY `idx_prod_dept` (`DEPARTAMENTO_ID_PRODUTO_VET`),
  KEY `idx_prod_unit` (`UNIDADE_ID_PRODUTO_VET`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

