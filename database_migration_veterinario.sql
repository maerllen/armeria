  `FABRICANTE_PRODUTO_VET` VARCHAR(128) DEFAULT NULL,
  `LOTE_PRODUTO_VET` VARCHAR(64) DEFAULT NULL,
  `VALOR_UNITARIO_PRODUTO_VET` DECIMAL(10,2) NOT NULL DEFAULT 0.00,
