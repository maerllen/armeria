SET FOREIGN_KEY_CHECKS = 0;

-- ------------------------------------------------------------------------------
-- 1. TABELA `USUARIOS`: COORDENAÇÃO DE CURSO E PERMISSÕES DE GESTÃO/CRIAÇÃO
-- ------------------------------------------------------------------------------
ALTER TABLE `USUARIOS`
  ADD COLUMN IF NOT EXISTS `COORDENACAO_CURSO_USUARIOS` TINYINT(1) NOT NULL DEFAULT 0 AFTER `SIGLA_PROFESSOR_USUARIOS`,
  ADD COLUMN IF NOT EXISTS `MATERIA_COORDENACAO_USUARIOS` VARCHAR(32) DEFAULT NULL AFTER `COORDENACAO_CURSO_USUARIOS`,
  ADD COLUMN IF NOT EXISTS `PODE_GERIR_FORMACAO_USUARIOS` TINYINT(1) NOT NULL DEFAULT 0 AFTER `MATERIA_COORDENACAO_USUARIOS`,
  ADD COLUMN IF NOT EXISTS `PODE_GERIR_CONTINUADO_USUARIOS` TINYINT(1) NOT NULL DEFAULT 0 AFTER `PODE_GERIR_FORMACAO_USUARIOS`,
  ADD COLUMN IF NOT EXISTS `PODE_CRIAR_CURSOS_USUARIOS` TINYINT(1) NOT NULL DEFAULT 0 AFTER `PODE_GERIR_CONTINUADO_USUARIOS`;

-- ------------------------------------------------------------------------------
-- 2. TABELA `CURSOS_ACADEMIA`: MÚLTIPLAS CARREIRAS E HORÁRIO DO MÓDULO CFTP
-- ------------------------------------------------------------------------------
ALTER TABLE `CURSOS_ACADEMIA`
  MODIFY COLUMN `CARREIRA_CURSOS_ACADEMIA` TEXT DEFAULT NULL;

ALTER TABLE `CURSOS_ACADEMIA`
  ADD COLUMN IF NOT EXISTS `CARREIRAS_CURSOS_ACADEMIA` JSON DEFAULT NULL AFTER `CARREIRA_CURSOS_ACADEMIA`,
  ADD COLUMN IF NOT EXISTS `DATA_FIM_CURSOS_ACADEMIA` DATE DEFAULT NULL AFTER `DATA_INICIO_CURSOS_ACADEMIA`,
  ADD COLUMN IF NOT EXISTS `MODULO_CURSOS_ACADEMIA` VARCHAR(100) DEFAULT NULL AFTER `NUMERO_MODULO_CURSOS_ACADEMIA`,
  ADD COLUMN IF NOT EXISTS `HORARIO_MODULO_CURSOS_ACADEMIA` JSON DEFAULT NULL AFTER `DISCIPLINA_CURSOS_ACADEMIA`,
  ADD COLUMN IF NOT EXISTS `HORARIO_ARQUIVO_NOME_CURSOS_ACADEMIA` VARCHAR(255) DEFAULT NULL AFTER `HORARIO_MODULO_CURSOS_ACADEMIA`;

-- ------------------------------------------------------------------------------
-- 3. TABELA `HORARIO_MODULO_CFTP`: REGISTROS NORMALIZADOS IMPORTADOS DO EXCEL
--    Colunas armazenadas: Data, Horário, Turma, Sigla, Disciplina, Sala
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS `HORARIO_MODULO_CFTP` (
  `ID_HORARIO_MODULO_CFTP` VARCHAR(64) NOT NULL,
  `CURSO_ID_HORARIO_MODULO_CFTP` VARCHAR(64) NOT NULL,
  `DATA_HORARIO_MODULO_CFTP` VARCHAR(32) DEFAULT NULL,
  `HORARIO_HORARIO_MODULO_CFTP` VARCHAR(100) DEFAULT NULL,
  `TURMA_HORARIO_MODULO_CFTP` VARCHAR(100) DEFAULT NULL,
  `SIGLA_HORARIO_MODULO_CFTP` VARCHAR(64) DEFAULT NULL,
  `DISCIPLINA_HORARIO_MODULO_CFTP` VARCHAR(255) DEFAULT NULL,
  `SALA_HORARIO_MODULO_CFTP` VARCHAR(128) DEFAULT NULL,
  `ORDEM_LINHA_HORARIO_MODULO_CFTP` INT NOT NULL DEFAULT 0,
  `DATA_CRIACAO_HORARIO_MODULO_CFTP` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`ID_HORARIO_MODULO_CFTP`),
  KEY `idx_hmc_curso` (`CURSO_ID_HORARIO_MODULO_CFTP`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

SET FOREIGN_KEY_CHECKS = 1;
