-- 5. TABELA `ACAUTELAR_ARMAS`: CONTROLE COMPLETO DE CAUTELA DE ARMAMENTO
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS `ACAUTELAR_ARMAS` (
  `ID_ACAUTELAR_ARMAS` VARCHAR(64) NOT NULL,
  `ARMA_ID_ACAUTELAR_ARMAS` VARCHAR(64) NOT NULL,
  `NUMERO_SERIE_ACAUTELAR_ARMAS` VARCHAR(128) NOT NULL,
  `MODELO_ACAUTELAR_ARMAS` VARCHAR(128) NOT NULL,
  `TIPO_ARMA_ACAUTELAR_ARMAS` VARCHAR(64) DEFAULT NULL,
  `CALIBRE_ACAUTELAR_ARMAS` VARCHAR(128) DEFAULT NULL,
  `QUANTIDADE_CARREGADORES_ACAUTELAR_ARMAS` INT NOT NULL DEFAULT 1,
  
  -- Localização original no cofre (local para onde a arma deve retornar)
  `COFRE_ORIGEM_ID_ACAUTELAR_ARMAS` VARCHAR(64) DEFAULT NULL,
  `DEPARTAMENTO_ID_ACAUTELAR_ARMAS` VARCHAR(64) DEFAULT NULL,
  `UNIDADE_ID_ACAUTELAR_ARMAS` VARCHAR(64) DEFAULT NULL,
  
  -- Dados do Solicitante (Policial)
  `REQUERENTE_ID_ACAUTELAR_ARMAS` VARCHAR(64) NOT NULL,
  `REQUERENTE_NOME_ACAUTELAR_ARMAS` VARCHAR(255) NOT NULL,
  `REQUERENTE_MASP_ACAUTELAR_ARMAS` VARCHAR(32) NOT NULL,
  `REQUERENTE_CARGO_ACAUTELAR_ARMAS` VARCHAR(64) DEFAULT NULL,
  `REQUERENTE_TELEFONE_ACAUTELAR_ARMAS` VARCHAR(32) DEFAULT NULL,
  `FINALIDADE_MOTIVO_ACAUTELAR_ARMAS` TEXT DEFAULT NULL,
  `DATA_SOLICITACAO_ACAUTELAR_ARMAS` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  
  -- Autorização do Armeiro
  `STATUS_ACAUTELAR_ARMAS` ENUM('PENDENTE', 'AUTORIZADA', 'DEVOLVIDA', 'RECUSADA') NOT NULL DEFAULT 'PENDENTE',
  `ARMEIRO_ID_ACAUTELAR_ARMAS` VARCHAR(64) DEFAULT NULL,
  `ARMEIRO_NOME_ACAUTELAR_ARMAS` VARCHAR(255) DEFAULT NULL,
  `ARMEIRO_MASP_ACAUTELAR_ARMAS` VARCHAR(32) DEFAULT NULL,
  `DATA_AUTORIZACAO_ACAUTELAR_ARMAS` DATETIME DEFAULT NULL,
  `OBSERVACOES_AUTORIZACAO_ACAUTELAR_ARMAS` TEXT DEFAULT NULL,

  -- Vínculo com munições retiradas em conjunto
  `CAUTELA_MUNICAO_ID_ACAUTELAR_ARMAS` VARCHAR(64) DEFAULT NULL,
  
  -- Dados da Devolução
  `DATA_DEVOLUCAO_ACAUTELAR_ARMAS` DATETIME DEFAULT NULL,
  `ARMEIRO_RECEBIMENTO_ID_ACAUTELAR_ARMAS` VARCHAR(64) DEFAULT NULL,
  `ARMEIRO_RECEBIMENTO_NOME_ACAUTELAR_ARMAS` VARCHAR(255) DEFAULT NULL,
  `ARMEIRO_RECEBIMENTO_MASP_ACAUTELAR_ARMAS` VARCHAR(32) DEFAULT NULL,
  `HOUVE_TIROS_ACAUTELAR_ARMAS` TINYINT(1) NOT NULL DEFAULT 0,
  `QUANTIDADE_TIROS_ACAUTELAR_ARMAS` INT NOT NULL DEFAULT 0,
  `CONDICOES_USO_ACAUTELAR_ARMAS` ENUM('Condições de Uso', 'Apresenta Defeito') NOT NULL DEFAULT 'Condições de Uso',
  `DESCRICAO_DEFEITO_ACAUTELAR_ARMAS` TEXT DEFAULT NULL,
  `APRESENTOU_PANE_ACAUTELAR_ARMAS` TINYINT(1) NOT NULL DEFAULT 0,
  `DESCRICAO_PANE_ACAUTELAR_ARMAS` TEXT DEFAULT NULL,
  `CARREGADORES_DEVOLVIDOS_ACAUTELAR_ARMAS` INT NOT NULL DEFAULT 1,
  `OBSERVACOES_DEVOLUCAO_ACAUTELAR_ARMAS` TEXT DEFAULT NULL,
  
  `DATA_CRIACAO_ACAUTELAR_ARMAS` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `DATA_ATUALIZACAO_ACAUTELAR_ARMAS` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`ID_ACAUTELAR_ARMAS`),
  KEY `idx_acaut_arma_id` (`ARMA_ID_ACAUTELAR_ARMAS`),
  KEY `idx_acaut_requerente` (`REQUERENTE_ID_ACAUTELAR_ARMAS`),
  KEY `idx_acaut_unidade` (`UNIDADE_ID_ACAUTELAR_ARMAS`),
  KEY `idx_acaut_status` (`STATUS_ACAUTELAR_ARMAS`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;


