-- Tabela dedicada: DESIGNACAO_EQUIPE_TURMA_CFTP
-- Vinculada a CURSOS_ACADEMIA, TURMAS_CFTP e EQUIPE_PROFESSORES_CURSO_FORMACAO
-- Compatível com MariaDB / phpMyAdmin (Idempotente)
-- ==============================================================================

SET FOREIGN_KEY_CHECKS = 0;

CREATE TABLE IF NOT EXISTS `DESIGNACAO_EQUIPE_TURMA_CFTP` (
  `ID_DESIGNACAO_EQUIPE_CFTP` VARCHAR(64) NOT NULL,
  `CURSO_ID_DESIGNACAO_EQUIPE_CFTP` VARCHAR(64) NOT NULL,
  `TURMA_CFTP_ID` VARCHAR(64) DEFAULT NULL,
  `TURMA` VARCHAR(64) NOT NULL,
  `CFTP` VARCHAR(255) NOT NULL,
  `MATERIA` VARCHAR(32) NOT NULL,
  `EQUIPE_ID` VARCHAR(64) NOT NULL,
  `APELIDO_EQUIPE` VARCHAR(100) NOT NULL,
  `PRIMEIRA_AULA` DATE NOT NULL,
  `ULTIMA_AULA` DATE NOT NULL,
  `PRIMEIRA_AULA_TURMA` DATE DEFAULT NULL,
  `ULTIMA_AULA_TURMA` DATE DEFAULT NULL,
  `CRIADO_POR_ID` VARCHAR(64) DEFAULT NULL,
  `CRIADO_POR_NOME` VARCHAR(255) DEFAULT NULL,
  `DATA_CRIACAO` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `DATA_ATUALIZACAO` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`ID_DESIGNACAO_EQUIPE_CFTP`),
  KEY `idx_detc_curso` (`CURSO_ID_DESIGNACAO_EQUIPE_CFTP`),
  KEY `idx_detc_turma_id` (`TURMA_CFTP_ID`),
  KEY `idx_detc_equipe` (`EQUIPE_ID`),
  KEY `idx_detc_curso_turma_mat` (`CURSO_ID_DESIGNACAO_EQUIPE_CFTP`, `TURMA`, `MATERIA`),
  CONSTRAINT `fk_detc_curso`
    FOREIGN KEY (`CURSO_ID_DESIGNACAO_EQUIPE_CFTP`)
    REFERENCES `CURSOS_ACADEMIA` (`ID_CURSOS_ACADEMIA`)
    ON DELETE CASCADE,
  CONSTRAINT `fk_detc_turma`
    FOREIGN KEY (`TURMA_CFTP_ID`)
    REFERENCES `TURMAS_CFTP` (`ID_TURMA_CFTP`)
    ON DELETE CASCADE,
  CONSTRAINT `fk_detc_equipe`
    FOREIGN KEY (`EQUIPE_ID`)
    REFERENCES `EQUIPE_PROFESSORES_CURSO_FORMACAO` (`ID_EQUIPE_PROFESSORES_CFTP`)
    ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

ALTER TABLE `DESIGNACAO_EQUIPE_TURMA_CFTP`
  MODIFY COLUMN `TURMA` VARCHAR(64) NOT NULL,
  ADD COLUMN IF NOT EXISTS `PRIMEIRA_AULA_TURMA` DATE DEFAULT NULL AFTER `ULTIMA_AULA`,
  ADD COLUMN IF NOT EXISTS `ULTIMA_AULA_TURMA` DATE DEFAULT NULL AFTER `PRIMEIRA_AULA_TURMA`;

SET FOREIGN_KEY_CHECKS = 1;
