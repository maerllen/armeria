SET FOREIGN_KEY_CHECKS = 0;

CREATE TABLE IF NOT EXISTS `EQUIPE_PROFESSORES_CURSO_FORMACAO` (
  `ID_EQUIPE_PROFESSORES_CFTP` VARCHAR(64) NOT NULL,
  `CURSO_ID_EQUIPE_PROFESSORES_CFTP` VARCHAR(64) NOT NULL,
  `MATERIA` VARCHAR(32) NOT NULL,
  `CFTP` VARCHAR(255) NOT NULL,
  `APELIDO_EQUIPE` VARCHAR(100) NOT NULL,
  `EQUIPE_01` VARCHAR(255) DEFAULT NULL,
  `EQUIPE_02` VARCHAR(255) DEFAULT NULL,
  `EQUIPE_03` VARCHAR(255) DEFAULT NULL,
  `EQUIPE_04` VARCHAR(255) DEFAULT NULL,
  `EQUIPE_05` VARCHAR(255) DEFAULT NULL,
  `EQUIPE_06` VARCHAR(255) DEFAULT NULL,
  `EQUIPE_01_ID` VARCHAR(64) DEFAULT NULL,
  `EQUIPE_02_ID` VARCHAR(64) DEFAULT NULL,
  `EQUIPE_03_ID` VARCHAR(64) DEFAULT NULL,
  `EQUIPE_04_ID` VARCHAR(64) DEFAULT NULL,
  `EQUIPE_05_ID` VARCHAR(64) DEFAULT NULL,
  `EQUIPE_06_ID` VARCHAR(64) DEFAULT NULL,
  `DATA_1` DATE NOT NULL,
  `DATA_2` DATE NOT NULL,
  `CRIADO_POR_ID` VARCHAR(64) DEFAULT NULL,
  `CRIADO_POR_NOME` VARCHAR(255) DEFAULT NULL,
  `DATA_CRIACAO` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `DATA_ATUALIZACAO` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`ID_EQUIPE_PROFESSORES_CFTP`),
  KEY `idx_epcf_curso` (`CURSO_ID_EQUIPE_PROFESSORES_CFTP`),
  KEY `idx_epcf_materia` (`MATERIA`),
  CONSTRAINT `fk_epcf_curso`
    FOREIGN KEY (`CURSO_ID_EQUIPE_PROFESSORES_CFTP`)
    REFERENCES `CURSOS_ACADEMIA` (`ID_CURSOS_ACADEMIA`)
    ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

SET FOREIGN_KEY_CHECKS = 1;
