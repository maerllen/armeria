-- 1) RELATORIOS_TREINAMENTO_POLICIAL -> DISPARO_REAL
SET @col_exists := (
  SELECT COUNT(*)
  FROM information_schema.COLUMNS
  WHERE TABLE_SCHEMA = DATABASE()
    AND TABLE_NAME = 'RELATORIOS_TREINAMENTO_POLICIAL'
    AND COLUMN_NAME = 'DISPARO_REAL'
);
SET @sql := IF(
  @col_exists = 0,
  'ALTER TABLE `RELATORIOS_TREINAMENTO_POLICIAL` ADD COLUMN `DISPARO_REAL` TINYINT(1) NOT NULL DEFAULT 0 AFTER `PARTICIPANTES_JSON`',
  'SELECT ''Coluna RELATORIOS_TREINAMENTO_POLICIAL.DISPARO_REAL já existe'' AS info'
);
PREPARE stmt FROM @sql;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

