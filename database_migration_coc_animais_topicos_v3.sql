-- 2. Coluna ANOTACOES_CONDUTOR_CACHORRO (500 caracteres) em CACHORROS_CANIL
SET @col_anot_exists := (
  SELECT COUNT(*) FROM information_schema.COLUMNS
   WHERE TABLE_SCHEMA = DATABASE()
     AND TABLE_NAME = 'CACHORROS_CANIL'
     AND COLUMN_NAME = 'ANOTACOES_CONDUTOR_CACHORRO'
);
SET @sql_add_anot := IF(
  @col_anot_exists = 0,
  'ALTER TABLE `CACHORROS_CANIL` ADD COLUMN `ANOTACOES_CONDUTOR_CACHORRO` VARCHAR(500) DEFAULT NULL AFTER `OBSERVACOES_CACHORRO`',
  'SELECT 1'
);
PREPARE stmt_add_anot FROM @sql_add_anot;
EXECUTE stmt_add_anot;
DEALLOCATE PREPARE stmt_add_anot;

-- 3. Tabela de Histórico de Condutores do Animal (Data Início e Data Fim)
CREATE TABLE IF NOT EXISTS `CACHORROS_CANIL_HISTORICO_CONDUTORES` (
  `ID_HIST_CONDUTOR` VARCHAR(64) NOT NULL,
  `CACHORRO_ID` VARCHAR(64) NOT NULL,
  `SLOT` TINYINT(1) NOT NULL DEFAULT 1,
  `CONDUTOR_ID` VARCHAR(64) DEFAULT NULL,
  `CONDUTOR_NOME` VARCHAR(255) NOT NULL,
  `CONDUTOR_MASP` VARCHAR(32) DEFAULT NULL,
  `CONDUTOR_CARGO` VARCHAR(128) DEFAULT NULL,
  `DATA_INICIO` VARCHAR(10) NOT NULL,
  `DATA_FIM` VARCHAR(10) DEFAULT NULL,
  `DATA_CRIACAO` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`ID_HIST_CONDUTOR`),
  KEY `idx_hist_cond_cachorro` (`CACHORRO_ID`),
  KEY `idx_hist_cond_usuario` (`CONDUTOR_ID`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Backfill idempotente do 1º e 2º condutores atuais caso o animal ainda não tenha histórico
INSERT INTO `CACHORROS_CANIL_HISTORICO_CONDUTORES` (
  `ID_HIST_CONDUTOR`, `CACHORRO_ID`, `SLOT`, `CONDUTOR_ID`, `CONDUTOR_NOME`, `CONDUTOR_MASP`, `CONDUTOR_CARGO`, `DATA_INICIO`, `DATA_FIM`
)
SELECT
  CONCAT('hcond-bf1-', c.`ID_CACHORRO`),
  c.`ID_CACHORRO`,
  1,
  c.`USUARIO_INTERNO_ID_CACHORRO`,
  c.`USUARIO_INTERNO_NOME_CACHORRO`,
  c.`USUARIO_INTERNO_MASP_CACHORRO`,
  c.`USUARIO_INTERNO_CARGO_CACHORRO`,
  DATE_FORMAT(COALESCE(c.`DATA_CRIACAO_CACHORRO`, NOW()), '%Y-%m-%d'),
  NULL
FROM `CACHORROS_CANIL` c
WHERE c.`TIPO_VINCULO_CACHORRO` = 'SISTEMA'
  AND c.`USUARIO_INTERNO_ID_CACHORRO` IS NOT NULL
  AND c.`USUARIO_INTERNO_NOME_CACHORRO` IS NOT NULL
  AND NOT EXISTS (
    SELECT 1 FROM `CACHORROS_CANIL_HISTORICO_CONDUTORES` h
    WHERE h.`CACHORRO_ID` = c.`ID_CACHORRO` AND h.`SLOT` = 1
  );

INSERT INTO `CACHORROS_CANIL_HISTORICO_CONDUTORES` (
  `ID_HIST_CONDUTOR`, `CACHORRO_ID`, `SLOT`, `CONDUTOR_ID`, `CONDUTOR_NOME`, `CONDUTOR_MASP`, `CONDUTOR_CARGO`, `DATA_INICIO`, `DATA_FIM`
)
SELECT
  CONCAT('hcond-bf2-', c.`ID_CACHORRO`),
  c.`ID_CACHORRO`,
  2,
  c.`USUARIO_INTERNO_2_ID_CACHORRO`,
  c.`USUARIO_INTERNO_2_NOME_CACHORRO`,
  c.`USUARIO_INTERNO_2_MASP_CACHORRO`,
  c.`USUARIO_INTERNO_2_CARGO_CACHORRO`,
  DATE_FORMAT(COALESCE(c.`DATA_CRIACAO_CACHORRO`, NOW()), '%Y-%m-%d'),
  NULL
FROM `CACHORROS_CANIL` c
WHERE c.`TIPO_VINCULO_CACHORRO` = 'SISTEMA'
  AND c.`USUARIO_INTERNO_2_ID_CACHORRO` IS NOT NULL
  AND c.`USUARIO_INTERNO_2_NOME_CACHORRO` IS NOT NULL
  AND NOT EXISTS (
    SELECT 1 FROM `CACHORROS_CANIL_HISTORICO_CONDUTORES` h
    WHERE h.`CACHORRO_ID` = c.`ID_CACHORRO` AND h.`SLOT` = 2
  );

-- 4. Tabela de Histórico de Vacinas do Animal
CREATE TABLE IF NOT EXISTS `CACHORROS_CANIL_VACINAS` (
  `ID_VACINA` VARCHAR(64) NOT NULL,
  `CACHORRO_ID` VARCHAR(64) NOT NULL,
  `NOME_VACINA` VARCHAR(160) NOT NULL,
  `DATA_APLICACAO` VARCHAR(10) NOT NULL,
  `PROXIMA_DOSE` VARCHAR(10) DEFAULT NULL,
  `LOTE` VARCHAR(80) DEFAULT NULL,
  `VETERINARIO` VARCHAR(160) DEFAULT NULL,
  `OBSERVACOES` TEXT DEFAULT NULL,
  `REGISTRADO_POR_ID` VARCHAR(64) DEFAULT NULL,
  `REGISTRADO_POR_NOME` VARCHAR(255) DEFAULT NULL,
  `DATA_CRIACAO` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`ID_VACINA`),
  KEY `idx_vac_cachorro` (`CACHORRO_ID`),
  KEY `idx_vac_proxima` (`PROXIMA_DOSE`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

