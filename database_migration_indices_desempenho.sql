  ADD COLUMN IF NOT EXISTS `AUSENCIA_INFORMADA` TINYINT(1) DEFAULT NULL COMMENT '1 = Ausência informada previamente; 0 = Não informada; NULL = Presente' AFTER `AUSENTE`;
