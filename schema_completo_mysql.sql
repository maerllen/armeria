ALTER TABLE `ACAUTELAR_MUNICOES` 
  MODIFY COLUMN `STATUS_ACAUTELAR_MUNICOES` VARCHAR(64) NOT NULL DEFAULT 'PENDENTE';

-- 19.2 Normalização de Cargos e Perfis de Usuários
ALTER TABLE `USUARIOS` 
  MODIFY COLUMN `CARGO_USUARIOS` VARCHAR(64) NOT NULL DEFAULT 'INVESTIGADOR',
  MODIFY COLUMN `PERFIL_USUARIOS` VARCHAR(64) NOT NULL DEFAULT 'Policial';

-- 19.3 Padronização de registros de cautela com status pendente de recibo
UPDATE `ACAUTELAR_ARMAS` 
SET `STATUS_ACAUTELAR_ARMAS` = 'PENDENTE'
WHERE `STATUS_ACAUTELAR_ARMAS` IN ('Cautela Pendente', 'Pendente de Recibo', 'Pendente Recibo');

UPDATE `ACAUTELAR_MUNICOES` 
SET `STATUS_ACAUTELAR_MUNICOES` = 'PENDENTE'
WHERE `STATUS_ACAUTELAR_MUNICOES` IN ('Cautela Pendente', 'Pendente de Recibo', 'Pendente Recibo');

-- 19.4 Sincroniza qualquer arma que esteja com status 'Cautela Pendente' ou 'Pendente de Recibo'
-- garantindo que conste em ACAUTELAR_ARMAS como PENDENTE para aparecer ao Armeiro
INSERT INTO `ACAUTELAR_ARMAS` (
  `ID_ACAUTELAR_ARMAS`,
  `ARMA_ID_ACAUTELAR_ARMAS`,
  `NUMERO_SERIE_ACAUTELAR_ARMAS`,
  `MODELO_ACAUTELAR_ARMAS`,
  `TIPO_ARMA_ACAUTELAR_ARMAS`,
  `CALIBRE_ACAUTELAR_ARMAS`,
  `QUANTIDADE_CARREGADORES_ACAUTELAR_ARMAS`,
  `COFRE_ORIGEM_ID_ACAUTELAR_ARMAS`,
  `DEPARTAMENTO_ID_ACAUTELAR_ARMAS`,
  `UNIDADE_ID_ACAUTELAR_ARMAS`,
  `REQUERENTE_ID_ACAUTELAR_ARMAS`,
  `REQUERENTE_NOME_ACAUTELAR_ARMAS`,
  `REQUERENTE_MASP_ACAUTELAR_ARMAS`,
  `REQUERENTE_CARGO_ACAUTELAR_ARMAS`,
  `FINALIDADE_MOTIVO_ACAUTELAR_ARMAS`,
  `STATUS_ACAUTELAR_ARMAS`,
  `DATA_SOLICITACAO_ACAUTELAR_ARMAS`,
  `DATA_CRIACAO_ACAUTELAR_ARMAS`
)
SELECT 
  CONCAT('caut-sync-', a.ID_ARMAS) AS `ID_ACAUTELAR_ARMAS`,
  a.ID_ARMAS AS `ARMA_ID_ACAUTELAR_ARMAS`,
  a.NUMERO_SERIE_ARMAS AS `NUMERO_SERIE_ACAUTELAR_ARMAS`,
  a.MODELO_ARMAS AS `MODELO_ACAUTELAR_ARMAS`,
  a.TIPO_ARMAS AS `TIPO_ARMA_ACAUTELAR_ARMAS`,
  a.CALIBRE_ARMAS AS `CALIBRE_ACAUTELAR_ARMAS`,
  COALESCE(a.QUANTIDADE_CARREGADORES_ARMAS, 2) AS `QUANTIDADE_CARREGADORES_ACAUTELAR_ARMAS`,
  a.COFRE_ID_ARMAS AS `COFRE_ORIGEM_ID_ACAUTELAR_ARMAS`,
  a.DEPARTAMENTO_ID_ARMAS AS `DEPARTAMENTO_ID_ACAUTELAR_ARMAS`,
  a.UNIDADE_ID_ARMAS AS `UNIDADE_ID_ACAUTELAR_ARMAS`,
  COALESCE(u.ID_USUARIOS, 'policial-sistema') AS `REQUERENTE_ID_ACAUTELAR_ARMAS`,
  COALESCE(u.NOME_USUARIOS, 'Policial Solicitante') AS `REQUERENTE_NOME_ACAUTELAR_ARMAS`,
  COALESCE(u.MASP_USUARIOS, '0000000') AS `REQUERENTE_MASP_ACAUTELAR_ARMAS`,
  COALESCE(u.CARGO_USUARIOS, 'INVESTIGADOR') AS `REQUERENTE_CARGO_ACAUTELAR_ARMAS`,
  'Solicitação pendente de recebimento pelo armeiro' AS `FINALIDADE_MOTIVO_ACAUTELAR_ARMAS`,
  'PENDENTE' AS `STATUS_ACAUTELAR_ARMAS`,
  NOW() AS `DATA_SOLICITACAO_ACAUTELAR_ARMAS`,
  NOW() AS `DATA_CRIACAO_ACAUTELAR_ARMAS`
FROM `ARMAS` a
LEFT JOIN `USUARIOS` u ON (
  u.UNIDADE_ID_USUARIOS = a.UNIDADE_ID_ARMAS
  AND (u.PERFIL_USUARIOS = 'Policial' OR u.CARGO_USUARIOS IN ('INVESTIGADOR', 'DELEGADO', 'PERITO', 'ESCRIVÃO'))
)
WHERE (
  LOWER(a.STATUS_ARMAS) LIKE '%pendente%' 
  OR a.STATUS_ARMAS IN ('Cautela Pendente', 'Pendente de Recibo', 'Pendente Recibo')
)
AND NOT EXISTS (
  SELECT 1 FROM `ACAUTELAR_ARMAS` ca 
  WHERE ca.ARMA_ID_ACAUTELAR_ARMAS = a.ID_ARMAS 
  AND ca.STATUS_ACAUTELAR_ARMAS IN ('PENDENTE', 'Cautela Pendente', 'Pendente de Recibo', 'Pendente Recibo')
)
GROUP BY a.ID_ARMAS;

SET FOREIGN_KEY_CHECKS = 1;

